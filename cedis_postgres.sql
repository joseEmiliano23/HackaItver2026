-- ---- TARIMA: ubicación en su rack y carga al embarque ----
CREATE OR REPLACE FUNCTION fn_tarima_valida() RETURNS trigger AS $$
DECLARE v_cap INTEGER; v_cargadas INTEGER;
BEGIN
    -- La ubicación debe ser del rack de su sucursal
    IF NEW.id_ubicacion IS NOT NULL AND
       (SELECT r.id_sucursal FROM ubicacion u JOIN rack r ON r.id_rack = u.id_rack
         WHERE u.id_ubicacion = NEW.id_ubicacion) <> NEW.id_sucursal THEN
        RAISE EXCEPTION 'La ubicación no pertenece al rack de la sucursal de la tarima';
    END IF;

    -- Al cargarla a un embarque
    IF NEW.id_embarque IS NOT NULL AND
       (TG_OP = 'INSERT' OR NEW.id_embarque IS DISTINCT FROM OLD.id_embarque) THEN
        IF (SELECT id_sucursal FROM embarque WHERE id_embarque = NEW.id_embarque) <> NEW.id_sucursal THEN
            RAISE EXCEPTION 'La tarima es de otra sucursal que el embarque';
        END IF;
        IF (SELECT estatus FROM embarque WHERE id_embarque = NEW.id_embarque) <> 'EN_ARMADO' THEN
            RAISE EXCEPTION 'El embarque ya no está en armado';
        END IF;
        SELECT tu.cap_tarimas INTO v_cap
          FROM embarque e JOIN unidad u ON u.id_unidad = e.id_unidad
          JOIN tipo_unidad tu ON tu.id_tipo = u.id_tipo
         WHERE e.id_embarque = NEW.id_embarque;
        SELECT COUNT(*) INTO v_cargadas FROM tarima
         WHERE id_embarque = NEW.id_embarque AND id_tarima <> NEW.id_tarima;
        IF v_cargadas >= v_cap THEN
            RAISE EXCEPTION 'El camión ya no tiene espacio (máximo % tarimas)', v_cap;
        END IF;
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_tarima_valida
BEFORE INSERT OR UPDATE OF id_ubicacion, id_embarque ON tarima
FOR EACH ROW EXECUTE FUNCTION fn_tarima_valida();

-- ---- EMBARQUE: andén de EMBARQUE, JEFE_EMBARQUE, unidad activa y regla del 90% ----
CREATE OR REPLACE FUNCTION fn_embarque_antes() RETURNS trigger AS $$
BEGIN
    IF (SELECT tipo FROM anden WHERE id_anden = NEW.id_anden) <> 'EMBARQUE' THEN
        RAISE EXCEPTION 'El embarque debe salir por un andén de EMBARQUE';
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF (SELECT rol FROM usuario WHERE id_usuario = NEW.id_jefe) <> 'JEFE_EMBARQUE' THEN
            RAISE EXCEPTION 'El embarque lo autoriza un usuario JEFE_EMBARQUE';
        END IF;
        IF NOT (SELECT activa FROM unidad WHERE id_unidad = NEW.id_unidad) THEN
            RAISE EXCEPTION 'La unidad no está activa';
        END IF;
    END IF;

    -- Regla del 90%: el camión no sale si no está lleno
    IF TG_OP = 'UPDATE' AND NEW.estatus = 'ENVIADO' AND OLD.estatus <> 'ENVIADO' THEN
        IF NOT (SELECT cumple_90 FROM v_llenado_embarque WHERE id_embarque = NEW.id_embarque) THEN
            RAISE EXCEPTION 'El camión no cubre el 90%% de su capacidad';
        END IF;
        NEW.fecha_salida := COALESCE(NEW.fecha_salida, now());
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_embarque_antes BEFORE INSERT OR UPDATE ON embarque
FOR EACH ROW EXECUTE FUNCTION fn_embarque_antes();

-- Al salir: bultos y tarimas embarcadas, y huecos del rack liberados
CREATE OR REPLACE FUNCTION fn_embarque_enviado() RETURNS trigger AS $$
BEGIN
    UPDATE bulto SET estatus = 'EMBARCADO'
    WHERE id_tarima IN (SELECT id_tarima FROM tarima WHERE id_embarque = NEW.id_embarque);

    UPDATE tarima SET estatus = 'EMBARCADA', id_ubicacion = NULL
    WHERE id_embarque = NEW.id_embarque;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_embarque_enviado AFTER UPDATE OF estatus ON embarque
FOR EACH ROW WHEN (NEW.estatus = 'ENVIADO' AND OLD.estatus <> 'ENVIADO')
EXECUTE FUNCTION fn_embarque_enviado();

