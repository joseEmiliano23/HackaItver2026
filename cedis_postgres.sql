-- =====================================================================
-- 1. CATÁLOGOS
-- =====================================================================

CREATE TABLE proveedor (
    id_proveedor  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfc           VARCHAR(13)  NOT NULL UNIQUE CHECK (length(rfc) IN (12, 13)),
    razon_social  VARCHAR(150) NOT NULL,
    contacto      VARCHAR(100),
    telefono      VARCHAR(20),
    email         VARCHAR(120)
);

CREATE TABLE sucursal (
    id_sucursal  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave        VARCHAR(10)  NOT NULL UNIQUE,
    nombre       VARCHAR(100) NOT NULL,
    direccion    VARCHAR(200),
    ciudad       VARCHAR(80)
);

CREATE TABLE producto (
    sku            VARCHAR(30)  PRIMARY KEY,
    descripcion    VARCHAR(150) NOT NULL,
    unidad_medida  VARCHAR(10)  NOT NULL DEFAULT 'PZA'
);

CREATE TABLE anden (
    id_anden  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero    INTEGER     NOT NULL CHECK (numero > 0),
    tipo      VARCHAR(10) NOT NULL CHECK (tipo IN ('RECIBO', 'EMBARQUE')),
    UNIQUE (numero, tipo)
);

CREATE TABLE tipo_unidad (
    id_tipo      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(40)   NOT NULL UNIQUE,
    cap_tarimas  INTEGER       NOT NULL CHECK (cap_tarimas > 0),
    cap_kg       NUMERIC(10,2) NOT NULL CHECK (cap_kg > 0),
    cap_m3       NUMERIC(10,2) NOT NULL CHECK (cap_m3 > 0)
);

-- =====================================================================
-- 2. TABLAS QUE DEPENDEN DE CATÁLOGOS
-- =====================================================================

CREATE TABLE usuario (
    id_usuario     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario        VARCHAR(40)  NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    nombre         VARCHAR(100) NOT NULL,
    rol            VARCHAR(15)  NOT NULL CHECK (rol IN
                     ('PROVEEDOR','OPERADOR','JEFE_EMBARQUE','SUCURSAL','GERENCIA')),
    id_proveedor   INTEGER REFERENCES proveedor(id_proveedor),
    id_sucursal    INTEGER REFERENCES sucursal(id_sucursal),
    CHECK (
        (rol = 'PROVEEDOR' AND id_proveedor IS NOT NULL AND id_sucursal IS NULL) OR
        (rol = 'SUCURSAL'  AND id_sucursal  IS NOT NULL AND id_proveedor IS NULL) OR
        (rol IN ('OPERADOR','JEFE_EMBARQUE','GERENCIA')
             AND id_proveedor IS NULL AND id_sucursal IS NULL)
    )
);

CREATE TABLE unidad (
    id_unidad  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    placas     VARCHAR(15) NOT NULL UNIQUE,
    id_tipo    INTEGER     NOT NULL REFERENCES tipo_unidad(id_tipo),
    activa     BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE rack (
    id_rack      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sucursal  INTEGER     NOT NULL UNIQUE REFERENCES sucursal(id_sucursal), -- 1 rack por sucursal
    codigo       VARCHAR(10) NOT NULL UNIQUE
);

CREATE TABLE ubicacion (
    id_ubicacion  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rack       INTEGER NOT NULL REFERENCES rack(id_rack),
    nivel         INTEGER NOT NULL CHECK (nivel    BETWEEN 1 AND 4),
    posicion      INTEGER NOT NULL CHECK (posicion BETWEEN 1 AND 8),
    UNIQUE (id_rack, nivel, posicion)
);

-- =====================================================================
-- 3. AGENDAMIENTO
-- =====================================================================

CREATE TABLE orden_compra (
    id_oc          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio_oc       VARCHAR(30) NOT NULL UNIQUE,
    id_proveedor   INTEGER     NOT NULL REFERENCES proveedor(id_proveedor),
    fecha_emision  DATE        NOT NULL,
    estatus        VARCHAR(15) NOT NULL DEFAULT 'EMITIDA' CHECK (estatus IN
                     ('EMITIDA','AGENDADA','EN_RECEPCION','RECIBIDA','CERRADA','CANCELADA'))
);

CREATE TABLE oc_detalle (
    id_oc_detalle       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_oc               INTEGER     NOT NULL REFERENCES orden_compra(id_oc),
    sku                 VARCHAR(30) NOT NULL REFERENCES producto(sku),
    id_sucursal         INTEGER     NOT NULL REFERENCES sucursal(id_sucursal),
    piezas_solicitadas  INTEGER     NOT NULL CHECK (piezas_solicitadas > 0),
    UNIQUE (id_oc, sku, id_sucursal)
);

CREATE TABLE factura (
    id_factura     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio_factura  VARCHAR(40) NOT NULL UNIQUE,                                -- no se repite
    id_oc          INTEGER     NOT NULL UNIQUE REFERENCES orden_compra(id_oc), -- 1 factura por OC
    fecha          DATE        NOT NULL
);

CREATE TABLE cita (
    id_cita      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_oc        INTEGER     NOT NULL REFERENCES orden_compra(id_oc),
    id_anden     INTEGER     NOT NULL REFERENCES anden(id_anden),
    fecha        DATE        NOT NULL,
    hora_inicio  TIME        NOT NULL CHECK (hora_inicio >= '08:00'),
    hora_fin     TIME        NOT NULL CHECK (hora_fin    <= '18:00'),
    estatus      VARCHAR(12) NOT NULL DEFAULT 'PROGRAMADA' CHECK (estatus IN
                   ('PROGRAMADA','EN_CURSO','COMPLETADA','CANCELADA','NO_SHOW')),
    CHECK (hora_fin - hora_inicio >= INTERVAL '1 hour')   -- descarga mínima de 1 hora
);

-- =====================================================================
-- 4. ALMACENAMIENTO Y EMBARQUE
-- =====================================================================

CREATE TABLE embarque (
    id_embarque   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folio         VARCHAR(30) NOT NULL UNIQUE,
    codigo_qr     VARCHAR(60) NOT NULL UNIQUE,
    id_sucursal   INTEGER     NOT NULL REFERENCES sucursal(id_sucursal),
    id_unidad     INTEGER     NOT NULL REFERENCES unidad(id_unidad),
    id_anden      INTEGER     NOT NULL REFERENCES anden(id_anden),
    id_jefe       INTEGER     NOT NULL REFERENCES usuario(id_usuario),
    fecha_salida  TIMESTAMPTZ,
    estatus       VARCHAR(10) NOT NULL DEFAULT 'EN_ARMADO' CHECK (estatus IN
                    ('EN_ARMADO','LISTO','ENVIADO','RECIBIDO')),
    ruta_pdf      VARCHAR(255)
);

CREATE TABLE tarima (
    id_tarima     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_qr     VARCHAR(60)  NOT NULL UNIQUE,
    id_sucursal   INTEGER      NOT NULL REFERENCES sucursal(id_sucursal),
    id_ubicacion  INTEGER      UNIQUE REFERENCES ubicacion(id_ubicacion),  -- una tarima por hueco
    id_embarque   INTEGER      REFERENCES embarque(id_embarque),
    altura_m      NUMERIC(4,2) NOT NULL CHECK (altura_m > 0 AND altura_m <= 1.85),
    estatus       VARCHAR(10)  NOT NULL DEFAULT 'ARMANDO' CHECK (estatus IN
                    ('ARMANDO','EN_RACK','EMBARCADA')),
    CHECK (estatus <> 'EN_RACK' OR id_ubicacion IS NOT NULL)
);

-- =====================================================================
-- 5. IDENTIFICACIÓN Y RECEPCIÓN
-- =====================================================================

CREATE TABLE bulto (
    id_bulto     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_qr    VARCHAR(60)   NOT NULL UNIQUE,
    id_factura   INTEGER       NOT NULL REFERENCES factura(id_factura),
    sku          VARCHAR(30)   NOT NULL REFERENCES producto(sku),      -- 1 producto por bulto
    id_sucursal  INTEGER       NOT NULL REFERENCES sucursal(id_sucursal),
    piezas       INTEGER       NOT NULL CHECK (piezas > 0),
    peso_kg      NUMERIC(10,2) NOT NULL CHECK (peso_kg > 0),
    volumen_m3   NUMERIC(10,3) NOT NULL CHECK (volumen_m3 > 0),
    id_tarima    INTEGER       REFERENCES tarima(id_tarima),
    estatus      VARCHAR(10)   NOT NULL DEFAULT 'DECLARADO' CHECK (estatus IN
                   ('DECLARADO','RECIBIDO','RECHAZADO','EN_TARIMA','EMBARCADO'))
);

CREATE TABLE recepcion (
    id_recepcion  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cita       INTEGER     NOT NULL UNIQUE REFERENCES cita(id_cita),  -- 1 recepción por cita
    id_operador   INTEGER     NOT NULL REFERENCES usuario(id_usuario),
    inicio        TIMESTAMPTZ NOT NULL DEFAULT now(),
    fin           TIMESTAMPTZ,
    estatus       VARCHAR(10) NOT NULL DEFAULT 'EN_PROCESO' CHECK (estatus IN ('EN_PROCESO','CERRADA'))
);

CREATE TABLE escaneo (
    id_escaneo    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_recepcion  INTEGER     NOT NULL REFERENCES recepcion(id_recepcion),
    id_bulto      INTEGER     REFERENCES bulto(id_bulto),   -- NULL si el QR no existe
    qr_leido      VARCHAR(60) NOT NULL,
    fecha_hora    TIMESTAMPTZ NOT NULL DEFAULT now(),
    resultado     VARCHAR(10) NOT NULL DEFAULT 'ACEPTADO' CHECK (resultado IN ('ACEPTADO','RECHAZADO')),
    motivo        VARCHAR(20) CHECK (motivo IN
                    ('SKU_NO_SOLICITADO','EXCEDENTE','QR_INVALIDO','DUPLICADO')),
    CHECK ( (resultado = 'ACEPTADO'  AND motivo IS NULL AND id_bulto IS NOT NULL) OR
            (resultado = 'RECHAZADO' AND motivo IS NOT NULL) )
);

-- Índices para las búsquedas más frecuentes
