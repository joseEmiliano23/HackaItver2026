-- Llenado de cada embarque y si ya puede salir (regla del 90%)
-- Volumen = espacio que ocupa cada tarima en el camión (1.12 x 1.15 x altura)
CREATE VIEW v_llenado_embarque WITH (security_invoker = true) AS
SELECT x.*,
       ROUND(100.0 * x.peso_kg    / x.cap_kg, 1) AS pct_peso,
       ROUND(100.0 * x.volumen_m3 / x.cap_m3, 1) AS pct_volumen,
       -- >>> REGLA DEL 90%: cambia OR por AND si se exigen ambos <<<
       (x.peso_kg >= 0.9 * x.cap_kg OR x.volumen_m3 >= 0.9 * x.cap_m3) AS cumple_90
FROM (
    SELECT e.id_embarque, e.folio, e.estatus, s.clave AS sucursal,
           un.placas, tu.nombre AS tipo_unidad,
           (SELECT COUNT(*) FROM tarima t WHERE t.id_embarque = e.id_embarque) AS tarimas,
           tu.cap_tarimas,
           (SELECT COALESCE(SUM(b.peso_kg), 0)
              FROM bulto b JOIN tarima t ON t.id_tarima = b.id_tarima
             WHERE t.id_embarque = e.id_embarque) AS peso_kg,
           tu.cap_kg,
           (SELECT COALESCE(SUM(1.12 * 1.15 * t.altura_m), 0)
              FROM tarima t WHERE t.id_embarque = e.id_embarque) AS volumen_m3,
           tu.cap_m3
    FROM embarque e
    JOIN sucursal s     ON s.id_sucursal = e.id_sucursal
    JOIN unidad un      ON un.id_unidad  = e.id_unidad
    JOIN tipo_unidad tu ON tu.id_tipo    = un.id_tipo
) x;

-- Solicitado vs. recibido por renglón de OC (faltantes)
CREATE VIEW v_faltantes_oc WITH (security_invoker = true) AS
SELECT oc.folio_oc, d.sku, p.descripcion, s.clave AS sucursal,
       d.piezas_solicitadas,
       COALESCE(SUM(b.piezas) FILTER (WHERE b.estatus IN ('RECIBIDO','EN_TARIMA','EMBARCADO')), 0)
           AS piezas_recibidas,
       d.piezas_solicitadas
         - COALESCE(SUM(b.piezas) FILTER (WHERE b.estatus IN ('RECIBIDO','EN_TARIMA','EMBARCADO')), 0)
           AS piezas_faltantes
FROM oc_detalle d
JOIN orden_compra oc ON oc.id_oc      = d.id_oc
JOIN producto p      ON p.sku         = d.sku
JOIN sucursal s      ON s.id_sucursal = d.id_sucursal
LEFT JOIN factura f  ON f.id_oc       = d.id_oc
LEFT JOIN bulto b    ON b.id_factura  = f.id_factura
                    AND b.sku         = d.sku
                    AND b.id_sucursal = d.id_sucursal
GROUP BY d.id_oc_detalle, oc.folio_oc, p.descripcion, s.clave;

-- Ocupación del rack de cada sucursal (32 posiciones)
CREATE VIEW v_ocupacion_rack WITH (security_invoker = true) AS
SELECT s.clave AS sucursal, r.codigo AS rack,
       COUNT(t.id_tarima) AS ocupadas,
       COUNT(u.id_ubicacion) - COUNT(t.id_tarima) AS libres,
       ROUND(100.0 * COUNT(t.id_tarima) / COUNT(u.id_ubicacion), 1) AS pct_ocupacion
FROM sucursal s
JOIN rack r        ON r.id_sucursal  = s.id_sucursal
JOIN ubicacion u   ON u.id_rack      = r.id_rack
LEFT JOIN tarima t ON t.id_ubicacion = u.id_ubicacion
GROUP BY s.id_sucursal, s.clave, r.codigo
ORDER BY s.clave;

-- Datos para imprimir la Relación de Embarque (PDF)
CREATE VIEW v_relacion_embarque WITH (security_invoker = true) AS
SELECT e.folio AS folio_embarque, e.codigo_qr AS qr_embarque,
       s.clave AS sucursal, s.nombre AS nombre_sucursal,
       un.placas, t.codigo_qr AS qr_tarima,
       b.codigo_qr AS qr_bulto, b.sku, p.descripcion, b.piezas, b.peso_kg
FROM embarque e
JOIN sucursal s ON s.id_sucursal = e.id_sucursal
JOIN unidad un  ON un.id_unidad  = e.id_unidad
JOIN tarima t   ON t.id_embarque = e.id_embarque
JOIN bulto b    ON b.id_tarima   = t.id_tarima
JOIN producto p ON p.sku         = b.sku
ORDER BY e.folio, t.codigo_qr, b.codigo_qr;

-- Agenda de andenes de recibo
CREATE VIEW v_agenda_andenes WITH (security_invoker = true) AS
SELECT c.fecha, a.numero AS anden, c.hora_inicio, c.hora_fin,
       pr.razon_social AS proveedor, oc.folio_oc, c.estatus
FROM cita c
JOIN anden a         ON a.id_anden      = c.id_anden
JOIN orden_compra oc ON oc.id_oc        = c.id_oc
JOIN proveedor pr    ON pr.id_proveedor = oc.id_proveedor
ORDER BY c.fecha, a.numero, c.hora_inicio;

-- Bultos rechazados en recepción
CREATE VIEW v_incidencias WITH (security_invoker = true) AS
SELECT e.fecha_hora, oc.folio_oc, pr.razon_social AS proveedor,
       e.qr_leido, b.sku, b.piezas, e.motivo
FROM escaneo e
JOIN recepcion r     ON r.id_recepcion  = e.id_recepcion
JOIN cita c          ON c.id_cita       = r.id_cita
JOIN orden_compra oc ON oc.id_oc        = c.id_oc
JOIN proveedor pr    ON pr.id_proveedor = oc.id_proveedor
LEFT JOIN bulto b    ON b.id_bulto      = e.id_bulto
WHERE e.resultado = 'RECHAZADO';

