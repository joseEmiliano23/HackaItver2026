-- ---- CITA: andén de RECIBO y sin empalmes ----
CREATE OR REPLACE FUNCTION fn_cita_valida() RETURNS trigger AS $$
BEGIN
    IF (SELECT tipo FROM anden WHERE id_anden = NEW.id_anden) <> 'RECIBO' THEN
        RAISE EXCEPTION 'La cita debe ser en un andén de RECIBO';
    END IF;

    IF NEW.estatus NOT IN ('CANCELADA','NO_SHOW') AND EXISTS (
        SELECT 1 FROM cita c
        WHERE c.id_cita  <> NEW.id_cita
          AND c.id_anden  = NEW.id_anden
          AND c.fecha     = NEW.fecha
          AND c.estatus NOT IN ('CANCELADA','NO_SHOW')
          AND NEW.hora_inicio < c.hora_fin
          AND c.hora_inicio   < NEW.hora_fin) THEN
        RAISE EXCEPTION 'EMPALME: el andén % ya tiene una cita en ese horario',
              (SELECT numero FROM anden WHERE id_anden = NEW.id_anden);
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_cita_valida
BEFORE INSERT OR UPDATE OF id_anden, fecha, hora_inicio, hora_fin, estatus ON cita
FOR EACH ROW EXECUTE FUNCTION fn_cita_valida();

-- Al agendar, la OC pasa a AGENDADA
CREATE OR REPLACE FUNCTION fn_cita_agenda_oc() RETURNS trigger AS $$
BEGIN
    UPDATE orden_compra SET estatus = 'AGENDADA'
    WHERE id_oc = NEW.id_oc AND estatus = 'EMITIDA';
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_cita_agenda_oc AFTER INSERT ON cita
FOR EACH ROW EXECUTE FUNCTION fn_cita_agenda_oc();

-- ---- RECEPCION: sólo OPERADOR; al iniciar/cerrar actualiza cita y OC ----
CREATE OR REPLACE FUNCTION fn_recepcion_antes() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' AND
       (SELECT rol FROM usuario WHERE id_usuario = NEW.id_operador) <> 'OPERADOR' THEN
        RAISE EXCEPTION 'La recepción debe hacerla un usuario OPERADOR';
    END IF;
    IF NEW.estatus = 'CERRADA' AND NEW.fin IS NULL THEN
        NEW.fin := now();
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_recepcion_antes BEFORE INSERT OR UPDATE ON recepcion
FOR EACH ROW EXECUTE FUNCTION fn_recepcion_antes();

CREATE OR REPLACE FUNCTION fn_recepcion_despues() RETURNS trigger AS $$
DECLARE v_oc INTEGER;
BEGIN
    SELECT id_oc INTO v_oc FROM cita WHERE id_cita = NEW.id_cita;
    IF TG_OP = 'INSERT' THEN
        UPDATE cita SET estatus = 'EN_CURSO' WHERE id_cita = NEW.id_cita;
        UPDATE orden_compra SET estatus = 'EN_RECEPCION' WHERE id_oc = v_oc;
    ELSIF NEW.estatus = 'CERRADA' AND OLD.estatus <> 'CERRADA' THEN
        UPDATE cita SET estatus = 'COMPLETADA' WHERE id_cita = NEW.id_cita;
        UPDATE orden_compra SET estatus = 'RECIBIDA' WHERE id_oc = v_oc;
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_recepcion_despues AFTER INSERT OR UPDATE OF estatus ON recepcion
FOR EACH ROW EXECUTE FUNCTION fn_recepcion_despues();

-- ---- ESCANEO: valida el bulto contra la OC ----
-- La app sólo inserta (id_recepcion, id_bulto, qr_leido). La base decide si se
-- ACEPTA o se RECHAZA y con qué motivo. Con "RETURNING resultado, motivo" la app
-- recibe la respuesta en el mismo INSERT para mostrar la alerta en la handheld.
CREATE OR REPLACE FUNCTION fn_escaneo_valida() RETURNS trigger AS $$
DECLARE
    b             bulto%ROWTYPE;
    v_oc_cita     INTEGER;
    v_oc_bulto    INTEGER;
    v_solicitadas INTEGER;
    v_recibidas   INTEGER;
BEGIN
    IF (SELECT estatus FROM recepcion WHERE id_recepcion = NEW.id_recepcion) <> 'EN_PROCESO' THEN
        RAISE EXCEPTION 'La recepción ya está cerrada';
    END IF;

    -- Si la app ya lo marcó como rechazado, se respeta
    IF NEW.resultado = 'RECHAZADO' THEN
        RETURN NEW;
    END IF;

    -- 1) El QR debe existir y ser de la OC de esta cita
    SELECT * INTO b FROM bulto WHERE id_bulto = NEW.id_bulto;
    SELECT c.id_oc INTO v_oc_cita
      FROM recepcion r JOIN cita c ON c.id_cita = r.id_cita
     WHERE r.id_recepcion = NEW.id_recepcion;
    SELECT f.id_oc INTO v_oc_bulto FROM factura f WHERE f.id_factura = b.id_factura;

    IF b.id_bulto IS NULL OR v_oc_bulto IS DISTINCT FROM v_oc_cita THEN
        NEW.resultado := 'RECHAZADO'; NEW.motivo := 'QR_INVALIDO';
        RETURN NEW;
    END IF;

    -- 2) No se acepta dos veces el mismo bulto
    IF EXISTS (SELECT 1 FROM escaneo WHERE id_bulto = NEW.id_bulto AND resultado = 'ACEPTADO') THEN
        NEW.resultado := 'RECHAZADO'; NEW.motivo := 'DUPLICADO';
        RETURN NEW;
    END IF;

    -- 3) El SKU y la sucursal deben estar en la OC
    SELECT piezas_solicitadas INTO v_solicitadas
      FROM oc_detalle
     WHERE id_oc = v_oc_cita AND sku = b.sku AND id_sucursal = b.id_sucursal;

    IF v_solicitadas IS NULL THEN
        NEW.resultado := 'RECHAZADO'; NEW.motivo := 'SKU_NO_SOLICITADO';
        RETURN NEW;
    END IF;

    -- 4) No se reciben más piezas de las solicitadas
    SELECT COALESCE(SUM(piezas), 0) INTO v_recibidas
      FROM bulto
     WHERE id_factura = b.id_factura AND sku = b.sku AND id_sucursal = b.id_sucursal
       AND estatus IN ('RECIBIDO','EN_TARIMA','EMBARCADO');

    IF v_recibidas + b.piezas > v_solicitadas THEN
        NEW.resultado := 'RECHAZADO'; NEW.motivo := 'EXCEDENTE';
        RETURN NEW;
    END IF;

    NEW.resultado := 'ACEPTADO'; NEW.motivo := NULL;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_escaneo_valida BEFORE INSERT ON escaneo
FOR EACH ROW EXECUTE FUNCTION fn_escaneo_valida();

-- Después del escaneo se actualiza el estatus del bulto
CREATE OR REPLACE FUNCTION fn_escaneo_estatus_bulto() RETURNS trigger AS $$
BEGIN
    IF NEW.resultado = 'ACEPTADO' THEN
        UPDATE bulto SET estatus = 'RECIBIDO' WHERE id_bulto = NEW.id_bulto;
    ELSIF NEW.id_bulto IS NOT NULL AND NEW.motivo IN ('SKU_NO_SOLICITADO','EXCEDENTE') THEN
        UPDATE bulto SET estatus = 'RECHAZADO'
        WHERE id_bulto = NEW.id_bulto AND estatus = 'DECLARADO';
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_escaneo_estatus_bulto AFTER INSERT ON escaneo
FOR EACH ROW EXECUTE FUNCTION fn_escaneo_estatus_bulto();

-- ---- BULTO -> TARIMA: recibido, misma sucursal, tarima no embarcada ----
CREATE OR REPLACE FUNCTION fn_bulto_a_tarima() RETURNS trigger AS $$
BEGIN
    IF NEW.id_tarima IS NOT NULL AND NEW.id_tarima IS DISTINCT FROM OLD.id_tarima THEN
        IF OLD.estatus NOT IN ('RECIBIDO','EN_TARIMA') THEN
            RAISE EXCEPTION 'Sólo se paletizan bultos RECIBIDOS';
        END IF;
        IF (SELECT id_sucursal FROM tarima WHERE id_tarima = NEW.id_tarima) <> NEW.id_sucursal THEN
            RAISE EXCEPTION 'La tarima es de otra sucursal';
        END IF;
        IF (SELECT estatus FROM tarima WHERE id_tarima = NEW.id_tarima) = 'EMBARCADA' THEN
            RAISE EXCEPTION 'La tarima ya fue embarcada';
        END IF;
        NEW.estatus := 'EN_TARIMA';
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;

